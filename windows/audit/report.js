function describe(snapshot){
 if(!snapshot||!Array.isArray(snapshot.sections))throw Error('Некорректный снимок.');
 const byId=new Map();for(const section of snapshot.sections){if(!section||typeof section.id!=='string'||byId.has(section.id)||!TOPICS.some(t=>t.id===section.id))throw Error('Некорректный раздел.');byId.set(section.id,section);}
 const sections=TOPICS.map(topic=>{
  const [title,purpose]=TOPIC_DETAILS[topic.id],source=byId.get(topic.id);
  if(!source)return {id:topic.id,title,purpose,status:'not-read',rows:[]};
  if(source.status!=='ok')return {id:topic.id,title,purpose,status:['auth','forbidden','unavailable','http-error'].includes(source.status)?source.status:'unknown',rows:[]};
  if(!Array.isArray(source.rows)||source.rows.length>2000)throw Error('Некорректные записи.');
  return {id:topic.id,title,purpose,status:'ok',rows:source.rows.map(row=>{
   if(!row||typeof row!=='object'||Array.isArray(row))throw Error('Некорректная запись.');
   return topic.fields.map(key=>{
    const desc=FIELDS[key];if(!desc)throw Error('Нет описания поля.');
    const present=Object.prototype.hasOwnProperty.call(row,key);const value=present?row[key]:null;
    if(present&&(typeof value!=='string'||value.length>512))throw Error('Некорректное значение.');
    return {key,label:desc[0],purpose:desc[1],present,value};
   });
  })};
 });
 return {complete:false,warning:'Отчёт неполный: многие разделы и поля, секреты и особенности оборудования не считываются. Отсутствующее поле не означает значение по умолчанию; чтение не является атомарным. Состояние и правила не подтверждают прохождение трафика.',sections};
}
